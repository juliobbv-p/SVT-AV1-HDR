ScanOrder eb_av1_scan_orders[TX_SIZES_ALL][3]; // filled at init by svt_aom_init_iscan()

// iscan tables are the inverse permutation of scan; generated at init from the scan
// tables instead of storing ~21 KB of const iscan tables.
extern const int32_t tx_size_wide[TX_SIZES_ALL];
extern const int32_t tx_size_high[TX_SIZES_ALL];
static int16_t       svt_iscan_pool[TX_SIZES_ALL][3][1024];
static int16_t       svt_mcol_pool[TX_SIZES_ALL][1024]; // column-major (mcol) scan, per-tx
static int16_t       svt_def_pool[TX_SIZES_ALL][1024]; // default (up-right diagonal) scan, per-tx
static int16_t       svt_id_scan[1024]; // row-major (mrow) scan == identity, shared for all tx

void svt_aom_init_iscan(void) {
    for (int i = 0; i < 1024; ++i) {
        svt_id_scan[i] = (int16_t)i;
    }
    for (int ts = 0; ts < TX_SIZES_ALL; ++ts) {
        int n = tx_size_2d[ts];
        if (ts == TX_64X64 || ts == TX_64X32 || ts == TX_32X64) {
            n = 1024;
        } else if (ts == TX_16X64 || ts == TX_64X16) {
            n = 512;
        }
        const int W = tx_size_wide[ts] < 32 ? tx_size_wide[ts] : 32;
        const int H = tx_size_high[ts] < 32 ? tx_size_high[ts] : 32;
        // mrow = identity (row-major)
        eb_av1_scan_orders[ts][1].scan = svt_id_scan;
        // mcol = column-major
        for (int k = 0; k < n; ++k) {
            svt_mcol_pool[ts][k] = (int16_t)((k % H) * W + (k / H));
        }
        eb_av1_scan_orders[ts][2].scan = svt_mcol_pool[ts];
        // default = up-right diagonal: tall(H>W) r-increasing, wide(W>H) r-decreasing,
        // square alternating (odd diag r-incr, even r-decr)
        {
            int idx = 0;
            for (int d = 0; d < W + H - 1; ++d) {
                const int rlo  = (d - (W - 1)) > 0 ? (d - (W - 1)) : 0;
                const int rhi  = d < (H - 1) ? d : (H - 1);
                int       incr = (H > W) ? 1 : (W > H) ? 0 : (d & 1);
                if (incr) {
                    for (int r = rlo; r <= rhi; ++r) {
                        svt_def_pool[ts][idx++] = (int16_t)(r * W + (d - r));
                    }
                } else {
                    for (int r = rhi; r >= rlo; --r) {
                        svt_def_pool[ts][idx++] = (int16_t)(r * W + (d - r));
                    }
                }
            }
        }
        eb_av1_scan_orders[ts][0].scan = svt_def_pool[ts];
        for (int v = 0; v < 3; ++v) {
            const int16_t* sc = eb_av1_scan_orders[ts][v].scan;
            int16_t*       is = svt_iscan_pool[ts][v];
            for (int i = 0; i < n; ++i) {
                is[sc[i]] = (int16_t)i;
            }
            eb_av1_scan_orders[ts][v].iscan = is;
        }
    }
}
